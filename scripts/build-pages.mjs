/**
 * Static build for the GitHub Pages preview  →  ./out
 *
 *   npm run build:pages                       (base path defaults to /institutional-portal)
 *   NEXT_PUBLIC_BASE_PATH= npm run build:pages (serve from a domain root)
 *
 * A static host cannot run the locale proxy, API routes or the catch-all 404
 * route, so they are moved aside for the duration of the build and always
 * restored afterwards. Filtering, search and the contact form switch to their
 * browser-side behaviour (NEXT_PUBLIC_STATIC_EXPORT=true).
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, renameSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const stash = path.join(root, ".pages-stash");
const serverOnly = ["src/proxy.ts", "src/app/api", "src/app/[locale]/[...rest]"];

const basePath = (process.env.NEXT_PUBLIC_BASE_PATH ?? "/institutional-portal").replace(/\/$/, "");
const env = {
  ...process.env,
  NEXT_PUBLIC_STATIC_EXPORT: "true",
  NEXT_PUBLIC_BASE_PATH: basePath,
  NEXT_PUBLIC_SITE_URL: process.env.NEXT_PUBLIC_SITE_URL ?? `https://orgestlikaj.github.io${basePath}`,
  CMS_SOURCE: "mock",
};

const moved = [];
let status = 1;
try {
  rmSync(stash, { recursive: true, force: true });
  // route types generated by `next dev` still reference the moved files; they are recreated on the next dev run
  rmSync(path.join(root, ".next", "dev", "types"), { recursive: true, force: true });
  for (const rel of serverOnly) {
    const from = path.join(root, rel);
    if (!existsSync(from)) continue;
    const to = path.join(stash, rel);
    mkdirSync(path.dirname(to), { recursive: true });
    renameSync(from, to);
    moved.push([from, to]);
  }

  const result = spawnSync("npx", ["next", "build"], { cwd: root, env, stdio: "inherit", shell: true });
  status = result.status ?? 1;

  if (status === 0) {
    const out = path.join(root, "out");
    // GitHub Pages: keep the _next folder (no Jekyll) and send the root to the Albanian homepage
    writeFileSync(path.join(out, ".nojekyll"), "");
    writeFileSync(
      path.join(out, "index.html"),
      `<!doctype html><html lang="sq"><head><meta charset="utf-8"><title>Duke ridrejtuar…</title>` +
        `<meta name="robots" content="noindex"><meta http-equiv="refresh" content="0; url=${basePath}/sq/">` +
        `<link rel="canonical" href="${basePath}/sq/"></head>` +
        `<body><a href="${basePath}/sq/">Shqip</a> · <a href="${basePath}/en/">English</a></body></html>\n`,
    );
    console.log(`\nStatic site ready in ./out (base path "${basePath || "/"}")`);
  }
} finally {
  for (const [from, to] of moved.reverse()) {
    mkdirSync(path.dirname(from), { recursive: true });
    renameSync(to, from);
  }
  rmSync(stash, { recursive: true, force: true });
}
process.exit(status);
